import { SemesterResult, StudentProfile } from '../types';
import { calculateCGPA, calculatePercentageFromCGPA } from '../utils/gradeCalculator';

export function generatePDFReport(semesters: SemesterResult[], profile: StudentProfile) {
  const overallCGPA = calculateCGPA(semesters);
  const overallPercentage = calculatePercentageFromCGPA(overallCGPA);

  const reportHTML = `
    <!DOCTYPE html>
    <html>
      <head>
        <title>CGPA Report - ${profile.studentName}</title>
        <style>
          @import url('https://fonts.googleapis.com/css2?family=Roboto:wght@300;400;500;700&display=swap');
          body {
            font-family: 'Roboto', sans-serif;
            margin: 0;
            padding: 30px;
            color: #1c1b1f;
            background: #fff;
          }
          .header {
            border-bottom: 2px solid #6750a4;
            padding-bottom: 15px;
            margin-bottom: 25px;
            display: flex;
            justify-content: space-between;
            align-items: center;
          }
          .title-area h1 {
            margin: 0;
            color: #6750a4;
            font-size: 26px;
          }
          .title-area p {
            margin: 4px 0 0 0;
            color: #49454f;
            font-size: 13px;
          }
          .badge {
            background: #e8def8;
            color: #1d192b;
            padding: 6px 14px;
            border-radius: 20px;
            font-weight: 700;
            font-size: 14px;
          }
          .profile-grid {
            display: grid;
            grid-template-columns: 1fr 1fr;
            gap: 15px;
            background: #f7f2fa;
            padding: 16px;
            border-radius: 12px;
            margin-bottom: 25px;
          }
          .profile-item {
            font-size: 13px;
          }
          .profile-item span {
            color: #49454f;
            font-weight: 500;
          }
          .summary-cards {
            display: grid;
            grid-template-columns: repeat(3, 1fr);
            gap: 15px;
            margin-bottom: 30px;
          }
          .card {
            border: 1px solid #e7e0ec;
            padding: 15px;
            border-radius: 12px;
            text-align: center;
          }
          .card-val {
            font-size: 28px;
            font-weight: 700;
            color: #6750a4;
          }
          .card-lbl {
            font-size: 12px;
            color: #49454f;
            margin-top: 4px;
          }
          .section-title {
            font-size: 18px;
            font-weight: 700;
            margin-bottom: 15px;
            color: #1c1b1f;
            border-left: 4px solid #6750a4;
            padding-left: 10px;
          }
          table {
            width: 100%;
            border-collapse: collapse;
            margin-bottom: 25px;
            font-size: 12px;
          }
          th {
            background: #e8def8;
            color: #1d192b;
            text-align: left;
            padding: 10px;
            font-weight: 700;
          }
          td {
            padding: 10px;
            border-bottom: 1px solid #e7e0ec;
          }
          tr:nth-child(even) {
            background: #fdf8fd;
          }
          .sem-header {
            background: #f3edf7;
            padding: 10px 14px;
            border-radius: 8px;
            margin-top: 20px;
            margin-bottom: 10px;
            display: flex;
            justify-content: space-between;
            align-items: center;
            font-weight: 700;
          }
          .footer {
            margin-top: 40px;
            text-align: center;
            font-size: 11px;
            color: #79747e;
            border-top: 1px solid #e7e0ec;
            padding-top: 15px;
          }
        </style>
      </head>
      <body>
        <div class="header">
          <div class="title-area">
            <h1>B.Tech Academic Performance Report</h1>
            <p>Generated by CGPA Calculator App</p>
          </div>
          <div class="badge">B.TECH CURRICULUM</div>
        </div>

        <div class="profile-grid">
          <div class="profile-item"><span>Student Name:</span> ${profile.studentName || 'N/A'}</div>
          <div class="profile-item"><span>Roll Number:</span> ${profile.rollNumber || 'N/A'}</div>
          <div class="profile-item"><span>Branch:</span> ${profile.branch || 'N/A'}</div>
          <div class="profile-item"><span>College:</span> ${profile.college || 'N/A'}</div>
        </div>

        <div class="summary-cards">
          <div class="card">
            <div class="card-val">${overallCGPA.toFixed(2)}</div>
            <div class="card-lbl">Cumulative GPA (CGPA)</div>
          </div>
          <div class="card">
            <div class="card-val">${overallPercentage.toFixed(2)}%</div>
            <div class="card-lbl">Equivalent Percentage</div>
          </div>
          <div class="card">
            <div class="card-val">${semesters.length}</div>
            <div class="card-lbl">Completed Semesters</div>
          </div>
        </div>

        <div class="section-title">Semester-wise Detailed Breakdown</div>

        ${semesters
          .map(
            (sem) => `
          <div class="sem-header">
            <span>${sem.semesterName}</span>
            <span>SGPA: ${sem.gpa.toFixed(2)} | Grade: ${sem.grade} | Credits: ${sem.totalCredits}</span>
          </div>
          <table>
            <thead>
              <tr>
                <th>Subject Name</th>
                <th>Credits</th>
                <th>Max Marks</th>
                <th>Obtained Marks</th>
                <th>Percentage</th>
                <th>Grade</th>
                <th>Grade Point</th>
              </tr>
            </thead>
            <tbody>
              ${sem.subjects
                .map((sub) => {
                  const pct = sub.obtainedMarks !== null ? ((sub.obtainedMarks / sub.maxMarks) * 100).toFixed(1) + '%' : '-';
                  return `
                    <tr>
                      <td><strong>${sub.name}</strong></td>
                      <td>${sub.credits}</td>
                      <td>${sub.maxMarks}</td>
                      <td>${sub.obtainedMarks ?? '-'}</td>
                      <td>${pct}</td>
                      <td><strong>${sub.grade || '-'}</strong></td>
                      <td>${sub.gradePoint !== undefined ? sub.gradePoint : '-'}</td>
                    </tr>
                  `;
                })
                .join('')}
            </tbody>
          </table>
        `
          )
          .join('')}

        <div class="footer">
          This transcript report was computed on ${new Date().toLocaleDateString()} using standard university credit-weighted SGPA/CGPA evaluation rules.
        </div>

        <script>
          window.onload = function() {
            window.print();
          }
        </script>
      </body>
    </html>
  `;

  const printWindow = window.open('', '_blank');
  if (printWindow) {
    printWindow.document.write(reportHTML);
    printWindow.document.close();
  }
}
